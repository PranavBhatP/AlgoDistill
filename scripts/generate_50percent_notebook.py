                "    @property\n",
                "    def error_message(self) -> Optional[str]:\n",
                "        if self.compilation_error:\n",
                "            return self.compilation_error\n",
                "        for tr in self.test_results:\n",
                "            if tr.error_message:\n",
                "                return tr.error_message\n",
                "        return None\n",
                "\n",
                "class SandboxJudge:\n",
                "    def __init__(self, default_timeout_s: float = 2.0, max_memory_mb: int = 512):\n",
                "        self.default_timeout_s = default_timeout_s\n",
                "        self.max_memory_mb = max_memory_mb\n",
                "\n",
                "    def _set_limits(self, memory_mb: int):\n",
                "        if sys.platform != \"win32\":\n",
                "            bytes_limit = memory_mb * 1024 * 1024\n",
                "            try:\n",
                "                resource.setrlimit(resource.RLIMIT_AS, (bytes_limit, bytes_limit))\n",
                "            except Exception:\n",
                "                pass\n",
                "\n",
                "    def evaluate_python_solution(self, code: str, test_cases: List[Dict[str, str]], timeout_s: Optional[float] = None) -> ExecutionResult:\n",
                "        timeout = timeout_s or self.default_timeout_s\n",
                "        if not test_cases:\n",
                "            return ExecutionResult(verdict=Verdict.AC, tests_passed=0, total_tests=0, pass_rate=1.0, max_runtime_ms=0.0)\n",
                "\n",
                "        try:\n",
                "            compile(code, \"<string>\", \"exec\")\n",
                "        except SyntaxError as e:\n",
                "            return ExecutionResult(verdict=Verdict.CE, tests_passed=0, total_tests=len(test_cases), pass_rate=0.0, max_runtime_ms=0.0, compilation_error=str(e))\n",
                "\n",
                "        with tempfile.NamedTemporaryFile(mode=\"w\", suffix=\".py\", delete=False) as script_file:\n",
                "            script_file.write(code)\n",
                "            script_path = script_file.name\n",
                "\n",
                "        try:\n",
                "            results = []\n",
                "            max_ms = 0.0\n",
                "            overall_verdict = Verdict.AC\n",
                "\n",
                "            for idx, tc in enumerate(test_cases):\n",
                "                inp = tc.get(\"input_data\", tc.get(\"input\", \"\"))\n",
                "                expected = tc.get(\"output_data\", tc.get(\"output\", \"\"))\n",
                "                start_t = time.perf_counter()\n",
                "                try:\n",
                "                    proc = subprocess.run(\n",
                "                        [sys.executable, script_path],\n",
                "                        input=inp, text=True, capture_output=True,\n",
                "                        timeout=timeout, preexec_fn=lambda: self._set_limits(self.max_memory_mb)\n",
                "                    )\n",
                "                    runtime_ms = (time.perf_counter() - start_t) * 1000.0\n",
                "                    max_ms = max(max_ms, runtime_ms)\n",
                "\n",
                "                    if proc.returncode != 0:\n",
                "                        verdict = Verdict.RE\n",
                "                        if overall_verdict == Verdict.AC: overall_verdict = Verdict.RE\n",
                "                        results.append(TestResult(idx, inp, expected, proc.stdout, verdict, runtime_ms, proc.stderr[:300]))\n",
