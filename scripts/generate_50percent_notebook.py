                "class ExecutionResult:\n",
                "    verdict: Verdict\n",
                "    tests_passed: int\n",
                "    total_tests: int\n",
                "    pass_rate: float\n",
                "    max_runtime_ms: float\n",
                "    test_results: List[TestResult] = field(default_factory=list)\n",
